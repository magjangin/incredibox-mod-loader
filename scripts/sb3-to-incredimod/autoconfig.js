'use strict';

// Draft a config.js from an extracted Scratch project, so a new project can be built right away.
// Everything here is a guess from the saved project state; lines marked TODO need a look.
// usage (module): autoConfig(project, sb3FileName) -> config.js source text

const median = (a) => {
  const s = [...a].sort((x, y) => x - y);
  return s.length ? s[Math.floor(s.length / 2)] : 0;
};

function slugify(name, i, used) {
  let s = String(name).toLowerCase().replace(/[^a-z0-9]+/g, '') || `char${i + 1}`;
  while (used.has(s)) s += 'x';
  used.add(s);
  return s;
}

function autoConfig(project, sb3Name) {
  const stage = project.targets[0];
  const chars = project.targets.slice(1, 21);
  const vars = Object.values(stage.variables || {});
  const findVar = (re) => vars.find((v) => re.test(v[0]));
  const notes = [];

  // Name: Scratch downloads turn ":" into "_"; drop "[tags]".
  const modName = String(sb3Name)
    .replace(/\.sb3$/i, '')
    .replace(/_ /g, ': ')
    .replace(/\s*\[[^\]]*\]/g, '')
    .trim();
  const platform = (project.meta && project.meta.platform && project.meta.platform.name) || 'Scratch';

  // Tempo: Sprunki/Interbox templates wait `Delay` seconds between Loop 1 / Loop 2 broadcasts.
  const delayVar = findVar(/^delay$/i);
  const delay = delayVar && Number(delayVar[1]) > 0 ? Number(delayVar[1]) : null;
  const loopSec = delay ? Math.round(delay * 1000) / 1000 : 4.8;
  const bpm = Math.round(960 / loopSec); // 16 beats per loop
  if (!delay) notes.push('no numeric "Delay" stage variable: loopSec/bpm are placeholders');

  // Horror phase: a "phase" variable and idle2 costumes.
  const hasPhase2 = !!findVar(/^phase$/i) && chars.filter((t) => t.costumes.some((c) => c.name === 'idle2')).length >= 10;
  if (hasPhase2) notes.push('phase 2 found: the saved Delay belongs to whichever phase was active when saved; check both tempos');

  // Slots: "Polo N" sprites, centered on stage x = 0.
  const polos = project.targets.filter((t) => /^Polo \d+$/.test(t.name)).sort((a, b) => a.x - b.x);
  const gaps = polos.slice(1).map((t, i) => t.x - polos[i].x);
  const slotUnits = gaps.length ? Math.round(median(gaps)) : 64;
  const slotY = polos.length ? Math.round(median(polos.map((t) => t.y))) : 0;
  if (!polos.length) notes.push('no "Polo N" sprites: slotUnits/slotY are placeholders');

  const backdrop = stage.costumes[stage.currentCostume || 0].name;
  const preview = project.targets.find((t) => t.name === 'Preview');
  const cover = preview ? preview.costumes[preview.currentCostume || 0].name : null;
  if (!preview) notes.push('no "Preview" sprite: the cover uses the backdrop');

  const used = new Set();
  const charLines = chars.map((t, i) => `    { slug: '${slugify(t.name, i, used)}' }, // ${i + 1} ${t.name.replace(/[\r\n]/g, ' ')}`);

  const frames = Math.round(loopSec * 24.2);
  const q = (s) => JSON.stringify(s);
  return `// Auto-generated by prepare.js from ${q(sb3Name)} - review the TODO lines, then build.
${notes.map((n) => `// TODO: ${n}`).join('\n')}
module.exports = {
  modName: ${q(modName)}, // also sets the versionId: do not rename after installing
  author: 'unknown', // TODO: original creator
  platform: ${q(platform)},
  source: '', // TODO: project or creator URL
  coverCostume: ${q(cover)},
  // Polo N sprites are ${slotUnits} stage units apart; fitTop nudges characters whose head leaves the frame
  framing: { mode: 'scratch', slotUnits: ${slotUnits}, charY: 253, panelY: 253, panelTarget: 'Polo 1', fitTop: true },
  background: { mode: 'stage', slotY: ${slotY} },
  panelCostume: {}, // {} = the game's default beatboxer in empty slots
  phases: {
    // Delay ${delay ? delay.toFixed(4) : '?'} s -> ${loopSec} s per loop, ${bpm} BPM
    1: { label: '', loopSec: ${loopSec}, bpm: ${bpm}, framesPerLoop: ${frames}, backdrop: ${q(backdrop)} },${
      hasPhase2
        ? `\n    // TODO: phase 2 tempo and backdrop\n    2: { label: ' (Horror)', loopSec: ${loopSec}, bpm: ${bpm}, framesPerLoop: ${frames}, backdrop: ${q(backdrop)} },`
        : ''
    }
  },
  // index = icon number - 1 (sprite order). Optional per character: idle (costume), dy (LD px, + = down)
  characters: [
${charLines.join('\n')}
  ],
};
`;
}

module.exports = { autoConfig };
